# 2. ETAPA DE EXTRAÇÃO: DEVOLVENDO JSON ESTRUTURADO
# ==========================================
def extrair_parametros_busca(solicitacao_usuario):
    """
    Usa o Gemini para analisar a frase do usuário e extrair os parâmetros de busca em formato JSON.
    """
    prompt_extracao = f"""
    Analise a seguinte solicitação de um cliente que busca um restaurante e extraia os parâmetros de busca no formato JSON estruturado abaixo.
    Identifique a culinária/tipo de comida e o bairro desejado.

    JSON schema de resposta:
    {{
        "culinaria": "tipo de culinária (ou null se não especificado)",
        "bairro": "bairro solicitado (ou null se não especificado)",
        "cidade": "cidade solicitada (padrão 'São Paulo' se não especificada)"
    }}

    Solicitação do usuário: "{solicitacao_usuario}"
    Retorne APENAS o JSON válido, sem markdown ou explicações.
    """
    try:
        response = client.models.generate_content(
            model='gemini-2.5-flash',
            contents=prompt_extracao,
            config={'response_mime_type': 'application/json'}
        )
        return json.loads(response.text.strip())
    except Exception as e:
        return {"culinaria": None, "bairro": None, "cidade": "São Paulo"}

